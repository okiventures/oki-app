  ACCESS_TOKEN=$(echo "$SIGNUP_BODY" | grep -o '"access_token":"[^"]*"' | cut -d'"' -f4)
  USER_ID=$(echo "$SIGNUP_BODY" | grep -o '"id":"[^"]*"' | head -1 | cut -d'"' -f4)

  if [ -n "$ACCESS_TOKEN" ] && [ -n "$USER_ID" ]; then
    pass "Handyman created: ${USER_ID}"

    # Convert user to handyman (need service_role to update user_type)
    if [ -n "${SUPABASE_SERVICE_ROLE_KEY:-}" ]; then
      curl -s -X PATCH "${SUPABASE_URL}/rest/v1/users?id=eq.${USER_ID}" \
        -H "apikey: ${SUPABASE_SERVICE_ROLE_KEY}" \
        -H "Authorization: Bearer ${SUPABASE_SERVICE_ROLE_KEY}" \
        -H "Content-Type: application/json" \
        -H "Prefer: return=minimal" \
        -d "{\"user_type\":\"handyman\"}" > /dev/null

      curl -s -X POST "${SUPABASE_URL}/rest/v1/handymen" \
        -H "apikey: ${SUPABASE_SERVICE_ROLE_KEY}" \
        -H "Authorization: Bearer ${SUPABASE_SERVICE_ROLE_KEY}" \
        -H "Content-Type: application/json" \
        -H "Prefer: return=minimal" \
        -d "{\"id\":\"${USER_ID}\",\"kyc_status\":\"PENDING\"}" > /dev/null

      pass "User promoted to handyman"
    fi
  else
    fail "Signup" "no access token in response"
  fi
else
  fail "Signup" "HTTP ${SIGNUP_CODE}: ${SIGNUP_BODY}"
fi

